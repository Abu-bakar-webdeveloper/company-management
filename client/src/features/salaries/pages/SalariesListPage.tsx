import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { Link } from 'react-router-dom'
import { toast } from 'sonner'
import { useAuth } from '@/features/auth/model/AuthContext'
import { userHasPermission } from '@/features/auth/model/permissions'
import { salariesApi } from '@/features/salaries/api/salariesApi'
import { filterSalaries } from '@/features/salaries/lib/salary-utils'
import type { Salary, SalaryListFilters, SalaryStats, SalaryStatus } from '@/features/salaries/model/types'
import { SalariesTable } from '@/features/salaries/ui/SalariesTable'
import { SalaryStatsRow } from '@/features/salaries/ui/SalaryStatsRow'
import { SalaryToolbar } from '@/features/salaries/ui/SalaryToolbar'
import { PlusIcon } from '@/features/salaries/ui/icons'
import { getErrorMessage } from '@/shared/api/errors'
import { paginate } from '@/shared/lib/pagination'

const PAGE_SIZE = 8

const now = new Date()

const defaultFilters: SalaryListFilters = {
  search: '',
  department: 'all',
  status: 'all',
  month: now.getMonth() + 1,
  year: now.getFullYear(),
  employeeId: 'all',
}

const emptyStats: SalaryStats = {
  totalMonthlyPayroll: 0,
  pendingPayroll: 0,
  paidThisMonth: 0,
  unpaidOnHold: 0,
}

export function SalariesListPage() {
  const { user } = useAuth()
  const canWrite = Boolean(user && userHasPermission(user, 'salaries:write'))
  const autoGeneratedRef = useRef(false)

  const [salaries, setSalaries] = useState<Salary[]>([])
  const [stats, setStats] = useState<SalaryStats>(emptyStats)
  const [incrementDue, setIncrementDue] = useState<
    {
      employeeId: string
      employeeName: string
      message: string
      stage: 'probation' | 'permanent'
      kind: 'probation_review' | 'increment_cycle'
      nextEligibleOn: string | null
    }[]
  >([])
  const [loading, setLoading] = useState(true)
  const [generating, setGenerating] = useState(false)
  const [filters, setFilters] = useState<SalaryListFilters>(defaultFilters)
  const [page, setPage] = useState(1)
  const [selectedIds, setSelectedIds] = useState<string[]>([])
  const [bulkLoading, setBulkLoading] = useState(false)

  const loadSalaries = useCallback(async () => {
    setLoading(true)
    try {
      const listParams: {
        month?: number
        year?: number
        status?: SalaryStatus
        employeeId?: string
        department?: string
        search?: string
      } = {}
      if (filters.month !== 'all') listParams.month = filters.month
      if (filters.year !== 'all') listParams.year = filters.year
      if (filters.status !== 'all') listParams.status = filters.status
      if (filters.employeeId !== 'all') listParams.employeeId = filters.employeeId
      if (filters.department !== 'all') listParams.department = filters.department
      if (filters.search.trim()) listParams.search = filters.search.trim()

      const statsParams =
        filters.month !== 'all' && filters.year !== 'all'
          ? { month: filters.month, year: filters.year }
          : filters.year !== 'all'
            ? { year: filters.year, month: new Date().getMonth() + 1 }
            : undefined

      const [data, statsData, due] = await Promise.all([
        salariesApi.list(listParams),
        salariesApi.getStats(statsParams),
        canWrite
          ? salariesApi.listIncrementDue().catch(() => [])
          : Promise.resolve([]),
      ])
      setSalaries(data)
      setStats(statsData)
      setIncrementDue(due)
    } catch (err) {
      toast.error(getErrorMessage(err, 'Unable to load salaries'))
    } finally {
      setLoading(false)
    }
  }, [filters, canWrite])

  const generateForSelectedPeriod = useCallback(
    async (opts?: { silent?: boolean }) => {
      const month =
        filters.month === 'all' ? new Date().getMonth() + 1 : filters.month
      const year = filters.year === 'all' ? new Date().getFullYear() : filters.year

      setGenerating(true)
      try {
        const result = await salariesApi.generateMonth({ month, year })
        if (!opts?.silent) {
          if (result.created > 0) {
            toast.success(
              `Added ${result.created} payroll record(s) for ${month}/${year}`,
            )
          } else {
            toast.message(`Payroll already up to date for ${month}/${year}`)
          }
        } else if (result.created > 0) {
          toast.success(`Monthly payroll ready — ${result.created} new record(s)`)
        }
        await loadSalaries()
        return result
      } catch (err) {
        if (!opts?.silent) {
          toast.error(getErrorMessage(err, 'Unable to generate monthly payroll'))
        }
        await loadSalaries()
        return null
      } finally {
        setGenerating(false)
      }
    },
    [filters.month, filters.year, loadSalaries],
  )

  useEffect(() => {
    void loadSalaries()
  }, [loadSalaries])

  useEffect(() => {
    if (!canWrite || autoGeneratedRef.current) return
    autoGeneratedRef.current = true
    void generateForSelectedPeriod({ silent: true })
  }, [canWrite, generateForSelectedPeriod])

  useEffect(() => {
    setPage(1)
    setSelectedIds([])
  }, [filters])

  const filtered = useMemo(() => filterSalaries(salaries, filters), [salaries, filters])
  const pagination = useMemo(() => paginate(filtered, page, PAGE_SIZE), [filtered, page])

  const isFiltered =
    filters.search.trim() !== '' ||
    filters.department !== 'all' ||
    filters.status !== 'all' ||
    filters.month !== defaultFilters.month ||
    filters.year !== defaultFilters.year ||
    filters.employeeId !== 'all'

  const showToolbar = !loading && !generating && (isFiltered || pagination.total > 0)

  const employeeOptions = useMemo(() => {
    const map = new Map<string, string>()
    for (const s of salaries) {
      map.set(s.employeeId, s.employeeName)
    }
    return Array.from(map.entries()).map(([id, name]) => ({ id, name }))
  }, [salaries])

  const toggleSelect = (id: string) => {
    setSelectedIds((prev) => (prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]))
  }

  const toggleSelectAll = () => {
    const pageIds = pagination.items.map((s) => s.id)
    const allSelected = pageIds.every((id) => selectedIds.includes(id))
    if (allSelected) {
      setSelectedIds((prev) => prev.filter((id) => !pageIds.includes(id)))
    } else {
      setSelectedIds((prev) => Array.from(new Set([...prev, ...pageIds])))
    }
  }

  const handleStatusChange = async (id: string, status: SalaryStatus) => {
    try {
      const updated = await salariesApi.updateStatus(id, status)
      setSalaries((prev) => prev.map((s) => (s.id === id ? updated : s)))
      const statsParams =
        filters.month !== 'all' && filters.year !== 'all'
          ? { month: filters.month, year: filters.year }
          : undefined
      const statsData = await salariesApi.getStats(statsParams)
      setStats(statsData)
      toast.success(`Status updated to ${status.replace('_', ' ')}`)
    } catch (err) {
      toast.error(getErrorMessage(err, 'Unable to update status'))
    }
  }

  const handleBulkMarkPaid = async () => {
    if (selectedIds.length === 0) return
    setBulkLoading(true)
    try {
      const result = await salariesApi.bulkUpdateStatus(selectedIds, 'paid')
      toast.success(`Marked ${result.updated} record(s) as paid`)
      setSelectedIds([])
      await loadSalaries()
    } catch (err) {
      toast.error(getErrorMessage(err, 'Unable to update selected records'))
    } finally {
      setBulkLoading(false)
    }
  }

  const periodLabel =
    filters.month !== 'all' && filters.year !== 'all'
      ? `${filters.month}/${filters.year}`
      : 'selected period'

  const probationDue = useMemo(
    () => incrementDue.filter((d) => d.kind === 'probation_review'),
    [incrementDue],
  )
  const incrementCycleDue = useMemo(
    () => incrementDue.filter((d) => d.kind === 'increment_cycle'),
    [incrementDue],
  )

  const ctaClassName =
    'inline-flex h-11 w-full shrink-0 items-center justify-center gap-2 rounded-lg px-5 text-sm font-semibold sm:w-auto'

  return (
    <div className="p-4 sm:p-6 lg:p-8">
      <header className="mb-6 flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <h1 className="text-2xl font-bold leading-8 text-heading sm:text-[30px] sm:leading-9">
            Salaries
          </h1>
          <p className="mt-1 text-sm leading-6 text-text-muted sm:text-base">
            Filter by month, generate payroll, and manage allowances under Payroll Settings.
          </p>
        </div>
        <div className="flex w-full flex-col gap-3 sm:w-auto sm:flex-row sm:flex-wrap sm:items-center">
          {canWrite && (
            <Link
              to="/salaries/settings"
              className={`${ctaClassName} border border-border bg-surface text-heading hover:bg-surface-muted`}
            >
              Payroll Settings
            </Link>
          )}
          {canWrite && selectedIds.length > 0 && (
            <button
              type="button"
              disabled={bulkLoading}
              onClick={() => void handleBulkMarkPaid()}
              className={`${ctaClassName} border border-[#D1FAE5] bg-[#ecfdf5] text-success hover:opacity-95 disabled:opacity-70`}
            >
              {bulkLoading ? 'Updating…' : `Mark Paid (${selectedIds.length})`}
            </button>
          )}
          {canWrite && (
            <>
              <button
                type="button"
                disabled={generating || filters.month === 'all' || filters.year === 'all'}
                onClick={() => void generateForSelectedPeriod()}
                className={`${ctaClassName} bg-primary text-white shadow-[0_4px_12px_rgba(24,119,242,0.25)] hover:opacity-95 disabled:opacity-70`}
              >
                {generating ? 'Generating…' : `Generate ${periodLabel}`}
              </button>
              <Link
                to="/salaries/new"
                className={`${ctaClassName} border border-border bg-surface text-heading hover:bg-surface-muted`}
              >
                <PlusIcon />
                Add One
              </Link>
            </>
          )}
        </div>
      </header>

      {incrementDue.length > 0 && (
        <div className="mb-4 space-y-3">
          {probationDue.length > 0 && (
            <div className="rounded-xl border border-[#fdba74] bg-[#fff7ed] px-4 py-3 text-sm text-heading">
              <p className="font-semibold">
                Probation completed — review due ({probationDue.length})
              </p>
              <p className="mt-1 text-text-muted">
                These employees finished their probation window. Confirm them as permanent and
                apply a package change if needed.
              </p>
              <ul className="mt-2 space-y-1">
                {probationDue.slice(0, 8).map((d) => (
                  <li key={d.employeeId}>
                    <Link
                      to={`/employees/${d.employeeId}?tab=salary`}
                      className="font-medium text-primary hover:underline"
                    >
                      {d.employeeName}
                    </Link>
                    <span className="text-text-muted"> — {d.message}</span>
                  </li>
                ))}
                {probationDue.length > 8 && (
                  <li className="text-text-muted">+{probationDue.length - 8} more</li>
                )}
              </ul>
            </div>
          )}
          {incrementCycleDue.length > 0 && (
            <div className="rounded-xl border border-[#93c5fd] bg-[#eff6ff] px-4 py-3 text-sm text-heading">
              <p className="font-semibold">
                Increment period due ({incrementCycleDue.length})
              </p>
              <p className="mt-1 text-text-muted">
                Permanent staff whose increment cycle has elapsed. Open their Salary tab → Change
                package to apply a raise (nothing is auto-applied).
              </p>
              <ul className="mt-2 space-y-1">
                {incrementCycleDue.slice(0, 8).map((d) => (
                  <li key={d.employeeId}>
                    <Link
                      to={`/employees/${d.employeeId}?tab=salary`}
                      className="font-medium text-primary hover:underline"
                    >
                      {d.employeeName}
                    </Link>
                    <span className="text-text-muted"> — {d.message}</span>
                  </li>
                ))}
                {incrementCycleDue.length > 8 && (
                  <li className="text-text-muted">+{incrementCycleDue.length - 8} more</li>
                )}
              </ul>
            </div>
          )}
        </div>
      )}

      <SalaryStatsRow stats={stats} />
      {showToolbar ? (
        <SalaryToolbar
          filters={filters}
          onChange={setFilters}
          employeeOptions={employeeOptions}
        />
      ) : null}

      {loading || generating ? (
        <div className="flex min-h-[280px] items-center justify-center rounded-xl border border-border-card bg-surface shadow-[var(--shadow-stat)]">
          <p className="text-sm text-text-muted">
            {generating ? 'Generating monthly payroll…' : 'Loading salaries…'}
          </p>
        </div>
      ) : (
        <SalariesTable
          salaries={pagination.items}
          page={pagination.currentPage}
          total={pagination.total}
          rangeStart={pagination.start}
          rangeEnd={pagination.end}
          totalPages={pagination.totalPages}
          onPageChange={setPage}
          selectedIds={selectedIds}
          onToggleSelect={toggleSelect}
          onToggleSelectAll={toggleSelectAll}
          onStatusChange={canWrite ? handleStatusChange : undefined}
          canWrite={canWrite}
          isFiltered={isFiltered}
        />
      )}
    </div>
  )
}
